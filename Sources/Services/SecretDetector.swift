import Foundation

/// Plain-Swift heuristics that decide whether a copied string is probably a secret.
enum SecretDetector {
    /// Pasteboard types password managers use to mark concealed or transient content.
    static let concealedTypes = ["org.nspasteboard.ConcealedType"]
    static let transientTypes = ["org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"]

    /// Well-known prefixes for API keys, tokens and private keys.
    static let keyPrefixes = [
        "sk-", "sk_live_", "sk_test_", "pk_live_", "rk_live_", "ghp_", "gho_", "ghu_", "ghs_", "github_pat_",
        "glpat-", "xoxb-", "xoxp-", "xoxa-", "AKIA", "ASIA", "AIza", "npm_", "SG.", "shpat_", "hf_",
        "-----BEGIN", "eyJhbGci"
    ]

    static func isSensitive(_ text: String) -> Bool {
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        return hasKeyPrefix(trimmed) || looksLikeCard(trimmed) || looksLikeToken(trimmed)
    }

    static func hasKeyPrefix(_ text: String) -> Bool {
        keyPrefixes.contains { text.hasPrefix($0) }
    }

    /// 13–19 digits (spaces/dashes allowed) that pass the Luhn checksum.
    static func looksLikeCard(_ text: String) -> Bool {
        guard text.allSatisfy({ $0.isNumber || $0 == " " || $0 == "-" }) else { return false }
        let digits = text.compactMap { $0.wholeNumberValue }
        guard (13...19).contains(digits.count) else { return false }
        return luhn(digits)
    }

    static func luhn(_ digits: [Int]) -> Bool {
        var sum = 0
        for (index, digit) in digits.reversed().enumerated() {
            if index % 2 == 1 {
                let doubled = digit * 2
                sum += doubled > 9 ? doubled - 9 : doubled
            } else {
                sum += digit
            }
        }
        return sum % 10 == 0
    }

    /// 32+ characters, no whitespace, mixed character classes and high entropy; URLs and paths are excluded.
    static func looksLikeToken(_ text: String) -> Bool {
        guard text.count >= 32, !text.contains(where: { $0.isWhitespace }) else { return false }
        if text.contains("://") || text.hasPrefix("/") || text.hasPrefix("~") { return false }
        let hasLetter = text.contains { $0.isLetter }
        let hasDigit = text.contains { $0.isNumber }
        guard hasLetter && hasDigit else { return false }
        return entropy(text) >= 3.5
    }

    /// Shannon entropy in bits per character.
    static func entropy(_ text: String) -> Double {
        var counts: [Character: Int] = [:]
        for ch in text { counts[ch, default: 0] += 1 }
        let length = Double(text.count)
        return counts.values.reduce(0) { total, count in
            let p = Double(count) / length
            return total - p * log2(p)
        }
    }
}
